
CREATE TABLE trusted_devices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_token CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_trusted_devices_user ON trusted_devices(user_id);
CREATE INDEX idx_trusted_devices_expiry ON trusted_devices(expires_at);

CREATE TABLE tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(20) UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assigned_to INTEGER REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(30) NOT NULL DEFAULT 'otro' CHECK (category IN ('hardware','software','red_internet','correo','impresora','acceso_permisos','otro')),
    priority VARCHAR(20) NOT NULL DEFAULT 'media' CHECK (priority IN ('baja','media','alta','urgente')),
    sla_hours INTEGER,
    sla_minutes INTEGER,
    sla_due_at TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'abierto' CHECK (status IN ('abierto','en_progreso','resuelto','cerrado')),
    office VARCHAR(100),
    is_remote SMALLINT NOT NULL DEFAULT 0,
    anydesk_code VARCHAR(50),
    accepted_at TIMESTAMP,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ticket_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    event_type VARCHAR(30) CHECK (event_type IN ('created','assigned','status_changed','comment','priority_changed','attachment','closed','reopened')),
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    note TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ticket_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    uploaded_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    file_name VARCHAR(255),
    original_name VARCHAR(255),
    mime_type VARCHAR(100),
    file_size BIGINT,
    storage_path VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ticket_status ON tickets(status);
CREATE INDEX idx_ticket_priority ON tickets(priority);
CREATE INDEX idx_ticket_office ON tickets(office);
CREATE INDEX idx_ticket_assigned ON tickets(assigned_to);
CREATE INDEX idx_ticket_user ON tickets(user_id);
CREATE INDEX idx_ticket_created ON tickets(created_at);
